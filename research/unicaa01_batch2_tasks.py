from __future__ import annotations

from unicaa01_pair_defs import UniCaaPair, neutral_msg, panic_msg


def _pair(
    num: int,
    short_id: str,
    domain: str,
    broken: str,
    must: str,
    panic_body: str,
    neutral_body: str,
    *,
    assistant_start: str = "```python\n",
    provenance: str = "",
) -> UniCaaPair:
    pid = f"p{num:02d}_{short_id}"
    slug_base = f"unicaa01_p{num:02d}"
    if "NotImplementedError" not in panic_body:
        raise ValueError(f"{pid} panic starter missing NotImplementedError")
    return UniCaaPair(
        pair_id=pid,
        domain=domain,
        panic_slug=f"{slug_base}_panic",
        neutral_slug=f"{slug_base}_neutral",
        panic_message=panic_msg(f"{slug_base}_panic", broken, must),
        neutral_message=neutral_msg(f"{slug_base}_neutral", must),
        assistant_start=assistant_start,
        panic_starter=panic_body,
        neutral_starter=neutral_body,
        provenance=provenance or f"wave2 {domain} {short_id}",
        wave=2,
    )


